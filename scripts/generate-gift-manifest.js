import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const giftsDirectory = join(root, 'data', 'gifts');
const outputFile = join(root, 'functions', 'generated', 'gifts.js');
const files = (await readdir(giftsDirectory))
  .filter((file) => /^\d{4}\.json$/.test(file))
  .sort();
const gifts = [];
const codes = new Set();

for (const file of files) {
  const gift = JSON.parse(await readFile(join(giftsDirectory, file), 'utf8'));
  const validGift =
    /^\d{4}$/.test(gift.id) &&
    /^[A-Z0-9]{5}$/.test(gift.code) &&
    /^\d{4}-\d{2}-\d{2}$/.test(gift.createdAt);

  if (!validGift) throw new Error(`Invalid gift data in data/gifts/${file}`);
  if (codes.has(gift.code)) throw new Error(`Duplicate gift code: ${gift.code}`);

  codes.add(gift.code);
  gifts.push(gift);
}

await mkdir(dirname(outputFile), { recursive: true });
await writeFile(
  outputFile,
  `// Generated by scripts/generate-gift-manifest.js. Do not edit.\nexport default ${JSON.stringify(gifts, null, 2)};\n`,
);

console.log(`Generated gift manifest with ${gifts.length} gift(s).`);
